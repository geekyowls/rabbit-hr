import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const contentDir = join(here, '..', 'src', 'content', 'help');
const outFile = join(contentDir, 'index.generated.ts');

function parseFrontmatter(raw) {
  const match = raw.match(/^---\s*\n([\s\S]*?)\n---\s*\n?([\s\S]*)$/);
  if (!match) {
    throw new Error('Missing frontmatter block');
  }

  const [, head, body] = match;
  const meta = {};

  for (const line of head.split('\n')) {
    const trimmed = line.trim();
    if (!trimmed) continue;
    const idx = trimmed.indexOf(':');
    if (idx === -1) continue;
    const key = trimmed.slice(0, idx).trim();
    let value = trimmed.slice(idx + 1).trim();

    if (value.startsWith('[') && value.endsWith(']')) {
      meta[key] = value
        .slice(1, -1)
        .split(',')
        .map((v) => v.trim().replace(/^["']|["']$/g, ''))
        .filter(Boolean);
    } else {
      meta[key] = value.replace(/^["']|["']$/g, '');
    }
  }

  return { meta, body: body.trim() };
}

const files = readdirSync(contentDir).filter((f) => f.endsWith('.md'));
const articles = [];

for (const file of files) {
  const raw = readFileSync(join(contentDir, file), 'utf8');
  const { meta, body } = parseFrontmatter(raw);
  const slug = file.replace(/\.md$/, '');

  if (!meta.title || !meta.category) {
    throw new Error(`${file}: title and category are required`);
  }

  articles.push({
    slug,
    title: meta.title,
    category: meta.category,
    order: Number(meta.order) || 0,
    tags: Array.isArray(meta.tags) ? meta.tags : [],
    excerpt: meta.excerpt || '',
    body,
  });
}

articles.sort(
  (a, b) =>
    a.category.localeCompare(b.category) ||
    a.order - b.order ||
    a.title.localeCompare(b.title),
);

const banner =
  '// AUTO-GENERATED by scripts/build-help-index.mjs. Do not edit by hand.\n' +
  '// Edit the markdown files in src/content/help and rerun `pnpm --filter frontend help:index`.\n';

const out =
  banner +
  "import type { HelpArticle } from './types';\n\n" +
  `export const HELP_ARTICLES: HelpArticle[] = ${JSON.stringify(articles, null, 2)};\n`;

writeFileSync(outFile, out);
console.log(
  `help index: wrote ${articles.length} articles to index.generated.ts`,
);
